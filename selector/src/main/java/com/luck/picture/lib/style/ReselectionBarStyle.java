package com.luck.picture.lib.style;

public class ReselectionBarStyle {
    /**
     * 背景色
     */
    private int barBackgroundColor;
    /**
     * 提示文字颜色
     */
    private int tipsTextColor;
    /**
     * 选择更多文字颜色
     */
    private int moreTextColor;
    /**
     * 提示文字大小
     */
    private int tipsTextSize;
    /**
     * 选择更多文字大小
     */
    private int moreTextSize;

    /**
     * 选择更多背景色
     */
    private int moreBackgroundColor;

    public int getBarBackgroundColor() {
        return barBackgroundColor;
    }

    public void setBarBackgroundColor(int barBackgroundColor) {
        this.barBackgroundColor = barBackgroundColor;
    }

    public int getTipsTextColor() {
        return tipsTextColor;
    }

    public void setTipsTextColor(int tipsTextColor) {
        this.tipsTextColor = tipsTextColor;
    }

    public int getMoreTextColor() {
        return moreTextColor;
    }

    public void setMoreTextColor(int moreTextColor) {
        this.moreTextColor = moreTextColor;
    }

    public int getTipsTextSize() {
        return tipsTextSize;
    }

    public void setTipsTextSize(int tipsTextSize) {
        this.tipsTextSize = tipsTextSize;
    }

    public int getMoreTextSize() {
        return moreTextSize;
    }

    public void setMoreTextSize(int moreTextSize) {
        this.moreTextSize = moreTextSize;
    }

    public int getMoreBackgroundColor() {
        return moreBackgroundColor;
    }

    public void setMoreBackgroundColor(int moreBackgroundColor) {
        this.moreBackgroundColor = moreBackgroundColor;
    }
}
